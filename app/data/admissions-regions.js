export function countriesForRegion(regionId) {
  return Object.entries(ADMISSION_COUNTRIES)
    .filter(([, c]) => c.region === regionId)
    .map(([name, c]) => ({ name, ...c }))
    .sort((a, b) => a.name.localeCompare(b.name, 'ar'));
}

export function regionForCountry(countryName) {
  const c = ADMISSION_COUNTRIES[countryName];
  return ADMISSION_REGIONS.find((r) => r.id === c?.region) || null;
}
