function step(partial) {
  return {
    id: partial.id,
    type: partial.type || 'action',
    name: partial.name || partial.actionKey || partial.type,
    actionKey: partial.actionKey || null,
    params: partial.params || {},
    approvalType: partial.approvalType || null,
    assignees: partial.assignees || ['owner', 'admin'],
    condition: partial.condition || null,
    thenSteps: partial.thenSteps || [],
    elseSteps: partial.elseSteps || [],
    parallelSteps: partial.parallelSteps || [],
    delayMs: partial.delayMs || 0,
    onFailure: partial.onFailure || 'stop',
    retries: partial.retries ?? 1,
    escalateAfterMinutes: partial.escalateAfterMinutes || 60,
  };
}

